"""Project review MCP. Stdout is reserved for JSON-RPC stdio transport."""
from __future__ import annotations

import argparse
import asyncio
import json

from jsonschema import Draft202012Validator
from mcp import types
from mcp.server.lowlevel import Server
from mcp.server.stdio import stdio_server

from core import ID, ROOT, Store


def obj(properties, required=()):
    return {"type": "object", "properties": properties, "required": list(required), "additionalProperties": False}


TEXT = {"type": "string", "minLength": 1, "maxLength": 8000}
IDENTIFIER = {"type": "string", "pattern": "^" + ID + "$"}
REVISION = {"type": "string", "pattern": "^[0-9a-f]{7,40}$"}
PATHS = {"type": "array", "items": {"type": "string", "minLength": 1}, "maxItems": 100, "uniqueItems": True}
ROOT_FIELD = {"expected_project_root": {"type": "string", "description": "Optional absolute root assertion; must match this checkout."}}
RECORD = {"type": "object", "required": ["schema_version", "id", "segment_id", "revision", "observed_at", "reviewer", "status", "scores", "score_reasons", "source", "report", "images"],
          "properties": {"schema_version": {"const": 1}, "id": IDENTIFIER, "segment_id": IDENTIFIER, "revision": REVISION,
                         "observed_at": TEXT, "reviewer": TEXT, "status": {"enum": ["blocked", "incomplete", "complete"]},
                         "scores": {"type": "array", "minItems": 7, "maxItems": 7, "items": {"type": ["number", "null"], "minimum": 0, "maximum": 10}},
                         "score_reasons": {"type": "array", "minItems": 7, "maxItems": 7, "items": {"type": "string"}},
                         "source": {"type": "object"}, "report": TEXT, "images": {"type": "array", "minItems": 1, "items": {"type": "object"}}}}
SCHEMAS = {
    "semantic_append": obj({**ROOT_FIELD, "work_id": IDENTIFIER, "summary": TEXT,
        "record": {"type":"object","required":["schema_version","id","segment_id","revision","evaluated_at","modality","group_id","observations","source_map","input_manifest","comparisons","conclusion","next_fix"],
        "properties":{"id":IDENTIFIER,"revision":REVISION}}}, ["work_id","summary","record"]),
    "progress_append": obj({**ROOT_FIELD, "event_id": IDENTIFIER, "work_id": IDENTIFIER, "segment_id": IDENTIFIER,
                            "kind": {"enum": ["change", "check", "complete"]}, "summary": TEXT, "result": TEXT,
                            "revision": REVISION, "evidence": PATHS,
                            "related_event_ids": {"type": "array", "items": IDENTIFIER, "uniqueItems": True, "maxItems": 1000}},
                           ["work_id", "segment_id", "kind", "summary", "result", "revision", "evidence"]),
    "review_append": obj({**ROOT_FIELD, "work_id": IDENTIFIER, "summary": TEXT, "record": RECORD}, ["work_id", "summary", "record"]),
    "flush": obj({**ROOT_FIELD, "full_render": {"type": "boolean", "default": False}}),
    "render": obj(ROOT_FIELD),
}
DESCRIPTIONS = {
    "semantic_append": "Append an immutable image blind-read comparison, with explicit text_masked_stills or original_subtitled_stills modality. Original-subtitle reviews distinguish visual observation and dialogue understanding and preserve every original pixel. Preserves independent Terra's raw guesses, source hashes, truth/difference/0-5-10 target scores and progress. Development image evaluation stays separate from title/new-game acceptance. Call render at segment closure.",
    "progress_append": "Append one immutable change/check event; complete separately confirms all event IDs for the same work. Retries with identical input are idempotent. Evidence paths must exist inside this project. Source PID is generated by the server.",
    "review_append": "Append an immutable independent Terra real-title/new-game seven-score review using existing validation, append its check event, then automatically render the full segment HTML. Completed render receipts deduplicate retries. Test sandboxes never render production pages.",
    "flush": "Atomically rebuild the lightweight YAML/JS snapshot. full_render=true runs the complete HTML exporter at a segment closure; routine events only refresh the bottom of the page.",
    "render": "Full HTML render at a segment closure, followed by an atomic live progress snapshot refresh.",
}


def execute(store, name, arguments):
    if name not in SCHEMAS:
        raise ValueError("Unknown review tool")
    Draft202012Validator(SCHEMAS[name]).validate(arguments)
    if name == "render":
        return store.flush(**arguments, full_render=True)
    return getattr(store, name)(**arguments)


async def main(options):
    store = Store(options.expected_project_root, options.test_sandbox)
    server = Server("dual-ontology-review", version="1.0.0", instructions=(
        "Bound exclusively to dual_ontology_world_reconstruct_2. After every modification and check, append a progress event. "
        "Confirm completed work with a separate complete event referencing its immutable event IDs. "
        "Independent Terra reviews require actual mainline provenance. Never fabricate receipts. "
        "At segment closure call render; routine progress automatically refreshes only the page bottom."))

    @server.list_tools()
    async def list_tools():
        return [types.Tool(name=name, description=DESCRIPTIONS[name], inputSchema=value) for name, value in SCHEMAS.items()]

    @server.call_tool()
    async def call_tool(name, arguments):
        try:
            result = await asyncio.to_thread(execute, store, name, arguments or {})
            return types.CallToolResult(content=[types.TextContent(type="text", text=json.dumps(result, ensure_ascii=False))], structuredContent=result)
        except Exception as error:
            return types.CallToolResult(isError=True, content=[types.TextContent(type="text", text=type(error).__name__ + ": " + str(error))])

    async with stdio_server() as (incoming, outgoing):
        await server.run(incoming, outgoing, server.create_initialization_options())


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--expected-project-root", default=str(ROOT))
    parser.add_argument("--test-sandbox", help="Integration tests only; must be below this project's .runtime/review-tests/")
    asyncio.run(main(parser.parse_args()))
