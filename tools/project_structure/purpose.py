GENERATED_DIRS = {'.git','.godot','.runtime','.pytest_cache','__pycache__','node_modules','bin','obj','.venv'}


def exclusion(path, root):
    p = Path(path)
    if p.suffix.lower() in ('.import','.uid'):
        return 'godot_metadata'
    if any(part.lower() in GENERATED_DIRS for part in p.parts[:-1]) or p.suffix.lower() in ('.pyc','.pyo'):
        return 'cache_build'
    if p.name.lower().endswith(('.designer.cs','.g.cs','.g.i.cs','.generated.cs','.assemblyinfo.cs')):
        file = root / p
        if file.is_file() and not file.is_symlink():
            with file.open('rb') as stream:
                if re.search(rb'<auto-generated|generated by a tool',stream.read(4096),re.I):
                    return 'generated_source'
    return ''


